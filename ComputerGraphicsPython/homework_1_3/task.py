def task7():
    a1, b1, g1 = 30, 90, 10
    a2, b2, g2 = 50, 90, 30
    R1 = functionals.get_R_euler_matrix_xyz(a1, b1, g1)
    R2 = functionals.get_R_euler_matrix_xyz(a2, b2, g2)
    print("Матриця R1:")
    print(R1)
    print("Матриця R2:")
    print(R2)
    print("Матриці однакові:")
    print(np.allclose(R1, R2))
    def extract(R):
        r11, r12, r13 = R[0]
        r21, r22, r23 = R[1]
        r31, r32, r33 = R[2]

        beta = math.asin(-r31)

        if abs(math.cos(beta)) > 1e-6:
            alpha = math.atan2(r32, r33)
            gamma = math.atan2(r21, r11)
        else:
            alpha = 0
            gamma = math.atan2(-r12, r22)
        return math.degrees(alpha), math.degrees(beta), math.degrees(gamma)
    print("Відновлені кути з R1:")
    print(extract(R1))
    print("Відновлені кути з R2:")
    print(extract(R2))